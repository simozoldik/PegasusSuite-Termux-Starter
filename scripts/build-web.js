#!/usr/bin/env node
/* Pegasus Suite — Capacitor web build.
 *
 * Copies the web frontend (frontend/) into the Capacitor webDir (www/), so the
 * Android app reuses the exact same UI/assets as the browser build.
 *
 * frontend/config.js is the authoritative runtime configuration (the backend
 * base URL the app calls). It is copied verbatim UNLESS PEGASUS_API_BASE_URL is
 * set, in which case www/config.js is regenerated with that value:
 *
 *     PEGASUS_API_BASE_URL=http://192.168.1.137:8710 npm run build
 *
 * SECURITY: only a public URL is written here. Never put credentials, API keys,
 * cookies or tokens in these files.
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const srcDir = path.join(root, 'frontend');
const outDir = path.join(root, 'www');

// Files/dirs that make up the shipped web app.
const ITEMS = [
  'index.html',
  'styles.css',
  'app.js',
  'config.js',
  'manifest.webmanifest',
  'sw.js',
  'icons',
];

function rmrf(p) {
  fs.rmSync(p, { recursive: true, force: true });
}

function normalizeBase(raw) {
  const v = String(raw || '').trim();
  if (!v) return '';
  return v.replace(/\/+$/, '');
}

function writeConfig(baseUrl, environment) {
  const body =
`/* GENERATED by scripts/build-web.js — DO NOT EDIT BY HAND.
 * Public backend base URL only (no secrets). See frontend/config.js. */
window.__PEGASUS_CONFIG__ = {
  apiBaseUrl: ${JSON.stringify(baseUrl)},
  environment: ${JSON.stringify(environment)}
};
`;
  fs.writeFileSync(path.join(outDir, 'config.js'), body, 'utf8');
}

function main() {
  const apiBase = normalizeBase(process.env.PEGASUS_API_BASE_URL);
  const environment = process.env.PEGASUS_ENV || (apiBase ? 'lab' : 'same-origin');

  if (!fs.existsSync(srcDir)) {
    console.error(`[build-web] ERROR: frontend/ not found at ${srcDir}`);
    process.exit(1);
  }

  rmrf(outDir);
  fs.mkdirSync(outDir, { recursive: true });

  for (const item of ITEMS) {
    const from = path.join(srcDir, item);
    const to = path.join(outDir, item);
    if (!fs.existsSync(from)) {
      console.warn(`[build-web] WARN: missing ${item}, skipped`);
      continue;
    }
    fs.cpSync(from, to, { recursive: true });
  }

  // frontend/config.js was copied above; override it only when an explicit base
  // URL is provided via the environment.
  if (apiBase) {
    writeConfig(apiBase, environment);
    console.log(`[build-web] OK  www/ ready. Backend API base = ${apiBase}/api`);
  } else {
    console.log('[build-web] www/config.js copied from frontend/config.js (no override).');
    console.log('[build-web] (set PEGASUS_API_BASE_URL to force a different backend base)');
  }
  console.log('[build-web] files:', fs.readdirSync(outDir).join(', '));
}

main();
